import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { ensureDeckGitignored } from "./gitignore.mjs";
import { tmp } from "./testkit.mjs";

test("does nothing without a .gitignore", () => {
  const root = tmp();
  assert.deepEqual(ensureDeckGitignored(root), { wrote: false, reason: "missing" });
  assert.ok(!fs.existsSync(path.join(root, ".gitignore")));
});

test("lists .ai/installed/ and the local link file once", () => {
  const root = tmp();
  fs.writeFileSync(path.join(root, ".gitignore"), "node_modules\n");
  assert.equal(ensureDeckGitignored(root).wrote, true);
  assert.equal(ensureDeckGitignored(root).wrote, false);
  const text = fs.readFileSync(path.join(root, ".gitignore"), "utf8");
  assert.equal(text, "node_modules\n\n# @pinkpuma/deck — local install\n.ai/installed/\nai-plugin.local.json\n");
});

test("an existing /.ai/installed entry counts", () => {
  const root = tmp();
  fs.writeFileSync(path.join(root, ".gitignore"), "/.ai/installed\nai-plugin.local.json\n");
  assert.equal(ensureDeckGitignored(root).wrote, false);
});

test("a lock line the user wrote outside deck's block stays", () => {
  const root = tmp();
  fs.writeFileSync(path.join(root, ".gitignore"), "# generated by ai-profile\nai-plugin.json\nai-plugin.lock.json\n");
  ensureDeckGitignored(root);
  const text = fs.readFileSync(path.join(root, ".gitignore"), "utf8");
  assert.match(text, /^# generated by ai-profile\nai-plugin\.json\nai-plugin\.lock\.json\n/);
  assert.match(text, /\.ai\/installed\//);
});
